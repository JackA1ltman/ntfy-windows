/// Join the emoji of all known tags with a space.
pub fn for_tags(tags: &[String]) -> String {
    let mut out: Vec<&'static str> = Vec::new();
    for tag in tags {
        if let Some(e) = emoji_for_tag(tag) {
            out.push(e);
        }
    }
    out.join(" ")
}
